"""Wrap the generated JSON into <script>-loadable JS.

Why: the workshop is meant to open by double-clicking a file, i.e. file://.
In that mode fetch() is blocked by CORS, so data/vanilla_cases.json and
icons/index.json can never load. Images are fine (an <img src> is not subject
to CORS), which means only these two JSON files need converting.

Output:
  web/data/vanilla_cases.js   window.PCBS2_VANILLA = {...}
  web/icons/index.js          window.PCBS2_ICONS   = {...}

Run after both extractors:
  python tools/export_icons.py   --game "<PCBS2 folder>"
  python tools/extract_vanilla.py --game "<PCBS2 folder>"
  python tools/build_data_js.py
"""
import json
import os
import sys


def wrap(src_json, dst_js, global_name):
    with open(src_json, encoding="utf-8") as fh:
        data = json.load(fh)
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))

    header = (
        "/* Generated by tools/build_data_js.py -- do not edit by hand.\n"
        " * Loaded via <script> so the workshop works from file:// where\n"
        " * fetch() would be blocked by CORS. */\n"
    )
    with open(dst_js, "w", encoding="utf-8") as fh:
        fh.write(header)
        fh.write("window.%s = %s;\n" % (global_name, payload))

    return os.path.getsize(dst_js), len(payload)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    web = os.path.join(os.path.dirname(here), "web")

    jobs = [
        ("data/vanilla_cases.json", "data/vanilla_cases.js", "PCBS2_VANILLA"),
        ("icons/index.json", "icons/index.js", "PCBS2_ICONS"),
    ]

    for rel_json, rel_js, gname in jobs:
        src = os.path.join(web, rel_json)
        dst = os.path.join(web, rel_js)
        if not os.path.isfile(src):
            sys.exit("missing %s - run the extractors first" % src)
        size, n = wrap(src, dst, gname)
        print("%-24s -> %-24s %8.0f KB  (window.%s)"
              % (rel_json, rel_js, size / 1024, gname))

    return 0


if __name__ == "__main__":
    sys.exit(main())